#!/usr/bin/env python3
# Run in the conda `rns` env by absolute path:
#   /Users/ell/opt/anaconda3/envs/rns/bin/python generate_msgpack_signed_fixtures.py > msgpack_signed_fixtures.json
#
# Drives the SAME codec RNS and LXMF use — RNS/vendor/umsgpack.py — so the vectors are genuine
# reference output, not a hand-rolled restatement of the spec.
#
# Three groups:
#
#   integers   Every boundary of umsgpack._pack_integer (umsgpack.py:288-314). This is the group
#              that answers the round-trip question: _pack_integer picks the encoding purely from
#              the VALUE (narrowest first), so a value-canonical Swift encoder must reproduce these
#              bytes exactly. Values are strings because Int64.min / UInt64.max do not survive a
#              JSON number in every decoder.
#
#   float32    umsgpack._pack_float (:325-333) does NOT choose from the value — it reads the module
#              global _float_precision, which is "double" whenever sys.float_info.mant_dig == 53
#              (:1177-1181), i.e. on every mainstream CPython. So reference NEVER emits 0xCA on its
#              own; force_float_precision="single" is the only way to get genuine umsgpack float32
#              bytes. That is exactly why Swift needs a distinct .float case: the width is not
#              recoverable from the value.
#
#   map32      A 65536-entry map — the smallest map umsgpack encodes as 0xDF. Recorded as a length
#              plus a sha256 rather than half a megabyte of hex; the sha256 is still a byte-compare.
#
# The LXMessage group is generated by generate_lxmf_signed_fixtures.py (it needs a real Identity).
import hashlib
import json

from RNS.vendor import umsgpack

INTEGERS = [
    # non-negative — must be untouched by the signed work
    0, 1, 127, 128, 255, 256, 65535, 65536,
    4294967295, 4294967296, 9223372036854775807, 18446744073709551615,
    # negative fixint boundary (0xE0-0xFF)
    -1, -31, -32,
    # int8 boundary (0xD0)
    -33, -127, -128,
    # int16 boundary (0xD1)
    -129, -32767, -32768,
    # int32 boundary (0xD2)
    -32769, -2147483647, -2147483648,
    # int64 boundary (0xD3)
    -2147483649, -9223372036854775807, -9223372036854775808,
]

integers = [
    {"value": str(v), "packed": umsgpack.packb(v).hex()}
    for v in INTEGERS
]

FLOATS = [0.0, 1.0, -1.0, 0.5, -2.5, 3.4028234663852886e38]
floats = [
    {
        "value": repr(v),
        "packed_single": umsgpack.packb(v, force_float_precision="single").hex(),
        "packed_double": umsgpack.packb(v, force_float_precision="double").hex(),
    }
    for v in FLOATS
]

# 65536 int-keyed entries: the smallest map umsgpack writes with the 0xDF (map32) header.
big_map = {k: k for k in range(65536)}
big_map_packed = umsgpack.packb(big_map)
assert big_map_packed[:5] == b"\xdf\x00\x01\x00\x00", big_map_packed[:5].hex()

# A hand-built map32 carrying a SINGLE pair. Non-canonical (umsgpack would use fixmap) but legal,
# and umsgpack decodes it — proof the 0xDF branch must accept any declared count, not just >65535.
small_map32 = b"\xdf\x00\x00\x00\x01" + umsgpack.packb(1) + umsgpack.packb(-1)
assert umsgpack.unpackb(small_map32) == {1: -1}

print(json.dumps({
    "integers": integers,
    "floats": floats,
    "map32_entry_count": len(big_map),
    "map32_packed_length": len(big_map_packed),
    "map32_packed_sha256": hashlib.sha256(big_map_packed).hexdigest(),
    "map32_packed_prefix": big_map_packed[:16].hex(),
    "small_map32_packed": small_map32.hex(),
}, indent=2))
